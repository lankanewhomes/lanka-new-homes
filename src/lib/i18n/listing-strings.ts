const DICTIONARIES: Record<SiteLanguage, Dictionary> = { en: {}, si, ta };

/** Translate a fixed UI string; unknown strings come back unchanged.
 * "3 Bed" / "2 Parking" translate the word and keep the number. */
export function translateListingString(language: SiteLanguage, text: string): string {
  if (language === "en") return text;
  const dict = DICTIONARIES[language];
  if (dict[text]) return dict[text];
  const numbered = text.match(/^(\d[\d,.–-]*)\s+(.+)$/);
  if (numbered && dict[numbered[2]]) return `${numbered[1]} ${dict[numbered[2]]}`;
  // "Move In 2030" / "Completed 2022" → word translated, year kept.
  const trailingYear = text.match(/^(.+?)\s+(\d{4})$/);
  if (trailingYear && dict[trailingYear[1]]) return `${dict[trailingYear[1]]} ${trailingYear[2]}`;
  return text;
}

/** "3-4" stays, "From Rs. 58,000,000" → "රු. 58,000,000 සිට": only the leading "From" word is localised. */
export function translateFromPrice(language: SiteLanguage, text: string): string {
  if (language === "en" || !text.startsWith("From ")) return text;
  const rest = text.slice(5);
  return language === "si" ? `${rest} ${si.From}` : `${rest} ${ta.From}`;
}
